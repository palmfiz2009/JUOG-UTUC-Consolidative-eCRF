"""Administrator-run OFFLINE generator; never installs keys or contacts services.
Run only on a trusted administrator workstation. Output is passphrase-encrypted.
No actual key generated by the agent. Dependencies: cryptography.
"""
import base64
import getpass
import hashlib
import hmac
import json
import os
import secrets
import warnings
from pathlib import Path
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from cryptography.hazmat.primitives.kdf.scrypt import Scrypt

SCRIPT = "11wSp4ePaP5b5A2b5ITZZSZa3YTe-Ex-Tu6oGlEkkRfkPrMCA4deVSZDy"
SHEET = "1Hd6EHDPZe8zGcDbILkaBLubgF5atfAzRfpPSN5LemiU"
AAD = b"JUOG-ISOLATED-ROTATION-BUNDLE-v1"

def material(root_bytes):
    if len(root_bytes) != 48:
        raise ValueError("ROOT_LENGTH_INVALID")
    root = base64.b64encode(root_bytes).decode("ascii")
    def derive(purpose):
        msg = f"JUOG-AUTH04-KEY-v1|{SCRIPT}|{SHEET}|{purpose}".encode()
        return base64.urlsafe_b64encode(hmac.new(root.encode(), msg, hashlib.sha256).digest()).decode().rstrip("=")
    return {"script_id": SCRIPT, "spreadsheet_id": SHEET,
            "gas": {"ADMIN_BRIDGE_SIGNING_KEY": root,
                    "ADMIN_RESUME_DERIVATION_KEY": derive("resume"),
                    "ADMIN_DRAFT_PEPPER": derive("draft-pepper")},
            "streamlit": {"juog_identity_bridge.signing_key": root}}

def encrypt_bundle(contents, password, salt, nonce):
    if len(password) < 20 or len(salt) != 16 or len(nonce) != 12:
        raise ValueError("ENCRYPTION_INPUT_INVALID")
    key = Scrypt(salt=salt, length=32, n=2**15, r=8, p=1).derive(password.encode())
    ciphertext = AESGCM(key).encrypt(nonce, json.dumps(contents, separators=(",", ":")).encode(), AAD)
    return {"format": AAD.decode(), "kdf": "scrypt-n32768-r8-p1", "salt": base64.b64encode(salt).decode(),
            "nonce": base64.b64encode(nonce).decode(), "ciphertext": base64.b64encode(ciphertext).decode()}

def main():
    # No environment variables, command-line password, clipboard or plaintext files.
    if not __import__("sys").stdin.isatty():
        raise ValueError("LOCAL_INTERACTIVE_TERMINAL_REQUIRED")
    warnings.simplefilter("error", getpass.GetPassWarning)
    password = getpass.getpass("New bundle passphrase (20+ characters; not a service key): ")
    if password != getpass.getpass("Confirm bundle passphrase: "):
        raise ValueError("PASSPHRASE_MISMATCH")
    bundle = encrypt_bundle(material(secrets.token_bytes(48)), password, secrets.token_bytes(16), secrets.token_bytes(12))
    destination = Path("juog-isolated-rotation.enc.json")
    fd = os.open(destination, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "w") as out:
        json.dump(bundle, out, separators=(",", ":"))
    print("ENCRYPTED_BUNDLE_CREATED; NOT_INSTALLED; no secret values printed")

if __name__ == "__main__":
    try:
        main()
    except Exception:
        # Fixed message only; never stringify exceptions or local objects.
        print("BUNDLE_NOT_CONFIRMED; STOP; no installation attempted")
        raise SystemExit(1) from None
